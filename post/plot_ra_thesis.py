
#!/usr/bin/env python3

"""
Critical Rayleigh number following Klaß, Figure 3.13.

Stage 1:
    Fit log(average kinetic energy) versus iteration.

Stage 2:
    Fit the growth rates versus Rayleigh number and find
    the zero crossing.

Reads ASCII VTI files generated by the TBGK solver.
"""

import argparse
import csv
import re
import xml.etree.ElementTree as ET

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


# ============================================================
# Read macroscopic fields and kinetic energy
# ============================================================

def read_vti(path):

    root = ET.parse(path).getroot()
    image = root.find(".//ImageData")

    if image is None:
        raise ValueError(f"Missing ImageData: {path}")

    extent = list(map(int, image.attrib["WholeExtent"].split()))

    nx = extent[1] - extent[0] + 1
    ny = extent[3] - extent[2] + 1

    arrays = {
        a.get("Name"): a
        for a in root.findall(".//PointData/DataArray")
    }

    names = ("Density", "Velocity", "Temperature")

    if not all(name in arrays for name in names):
        raise ValueError(f"Missing physical fields: {path}")

    rho = np.fromstring(
        arrays["Density"].text or "", sep=" "
    ).reshape(ny, nx)

    velocity = np.fromstring(
        arrays["Velocity"].text or "", sep=" "
    ).reshape(ny, nx, 3)[:, :, :2]

    T = np.fromstring(
        arrays["Temperature"].text or "", sep=" "
    ).reshape(ny, nx)

    if not (
        np.isfinite(rho).all()
        and np.isfinite(velocity).all()
        and np.isfinite(T).all()
    ):
        raise ValueError(f"Nonfinite fields: {path}")

    if (rho <= 0).any() or (T <= 0).any():
        raise ValueError(f"Nonpositive density or temperature: {path}")

    # ========================================================
    # Total average kinetic energy (thesis methodology)
    # ========================================================

    Etotal = 0.5 * np.mean(
        rho * np.sum(velocity**2, axis=2)
    )

    # ========================================================
    # Fluctuating kinetic energy
    #
    # Remove horizontal mean at every vertical location.
    # Used to detect whether a convective signal exists.
    # ========================================================

    ufluc = velocity - velocity.mean(axis=1, keepdims=True)

    Efluc = 0.5 * np.mean(
        rho * np.sum(ufluc**2, axis=2)
    )

    maxSpeed = np.sqrt(np.sum(velocity**2, axis=2)).max()

    # Horizontal temperature variation
    temperatureSpan = np.max(np.ptp(T, axis=1))

    return Etotal, Efluc, maxSpeed, temperatureSpan


# ============================================================
# Read all VTI files for one Rayleigh number
# ============================================================

def load_case(folder):

    files = []

    for path in (folder / "vti").glob("rb_*.vti"):

        match = re.fullmatch(r"rb_(\d+)\.vti", path.name)

        if match:
            files.append((int(match.group(1)), path))

    files.sort()

    if not files:
        raise FileNotFoundError(f"No VTI files in {folder / 'vti'}")

    samples = [
        (step, *read_vti(path))
        for step, path in files
    ]

    return np.asarray(samples, dtype=float)


# ============================================================
# Main analysis
# ============================================================

def main():

    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
        "--root",
        type=Path,
        default=Path("results/rb/NX_200_NY_100")
    )

    parser.add_argument("--fit-start", type=int, required=True)
    parser.add_argument("--fit-end", type=int, required=True)

    parser.add_argument(
        "--ra",
        type=float,
        nargs="*",
        help="Rayleigh numbers to include"
    )

    parser.add_argument(
        "--energy",
        choices=("total", "fluct"),
        default="total"
    )

    parser.add_argument(
        "--min-fluct-energy",
        type=float,
        default=1e-25
    )

    parser.add_argument(
        "--min-r2",
        type=float,
        default=0.98
    )

    args = parser.parse_args()

    if args.fit_end <= args.fit_start:
        parser.error("Invalid fitting interval")

    # ========================================================
    # Find Rayleigh cases
    # ========================================================

    requested = set(args.ra) if args.ra else None
    cases = []

    for folder in args.root.glob("Ra_*"):

        try:
            ra = float(folder.name[3:])
        except ValueError:
            continue

        if requested is None or ra in requested:
            cases.append((ra, folder))

    cases.sort()

    if not cases:
        parser.error("No matching Rayleigh cases found")

    # ========================================================
    # Output directory
    # ========================================================

    output = args.root / "critical_thesis"
    output.mkdir(parents=True, exist_ok=True)

    # ========================================================
    # Figure 3.13-style panels
    # ========================================================

    fig, (ax1, ax2) = plt.subplots(
        1, 2, figsize=(12, 4.8)
    )

    growthRates = []
    summary = []

    # ========================================================
    # Stage 1: Fit log(E) versus iteration
    # ========================================================

    for ra, folder in cases:

        try:
            data = load_case(folder)
        except (FileNotFoundError, ValueError) as error:
            print(f"Ra={ra:g}: {error}")
            continue

        iteration, Etotal, Efluc, maxSpeed, Tspan = data.T

        E = Etotal if args.energy == "total" else Efluc

        mask = (
            (iteration >= args.fit_start)
            & (iteration <= args.fit_end)
            & (E > 0.0)
        )

        n = int(np.count_nonzero(mask))

        medianFluc = float(np.median(Efluc[mask])) if n else np.nan
        medianTotal = float(np.median(Etotal[mask])) if n else np.nan

        fraction = (
            medianFluc / medianTotal
            if medianTotal > 0.0 else np.nan
        )

        line, = ax1.plot(
            iteration,
            np.log(np.maximum(E, np.finfo(float).tiny)),
            ".-",
            linewidth=1.1,
            markersize=3,
            label=f"Ra = {ra:g}"
        )

        color = line.get_color()

        print(f"\nRa = {ra:g}")
        print(f"Initial horizontal T variation = {Tspan[0]:.6e}")
        print(f"Median fluctuating energy      = {medianFluc:.6e}")
        print(f"Fluctuating / total energy     = {fraction:.6e}")

        if n < 5:
            print("Insufficient samples for fitting")
            summary.append(
                [ra, np.nan, np.nan, np.nan, medianFluc, "too_few"]
            )
            continue

        if medianFluc < args.min_fluct_energy:
            print("No resolved convective signal")
            summary.append(
                [ra, np.nan, np.nan, np.nan, medianFluc, "unresolved"]
            )
            continue

        x = iteration[mask]
        y = np.log(E[mask])

        gamma, intercept = np.polyfit(x, y, 1)

        yfit = gamma * x + intercept

        residual = y - yfit

        sse = np.sum(residual**2)
        sst = np.sum((y - y.mean())**2)

        r2 = 1.0 - sse / sst if sst > 0 else 0.0

        sxx = np.sum((x - x.mean())**2)

        gammaError = np.sqrt(
            sse / (n - 2) / sxx
        )

        ax1.plot(
            x, yfit, "--",
            color=color,
            linewidth=2
        )

        status = (
            "accepted"
            if r2 >= args.min_r2
            else "nonlinear_or_noisy"
        )

        print(f"Growth rate / iteration = {gamma:+.9e}")
        print(f"Slope standard error    = {gammaError:.6e}")
        print(f"R²                      = {r2:.6f}")
        print(f"Status                  = {status}")

        if abs(gamma) <= 3.0 * gammaError:
            print("Warning: slope is not clearly different from zero")

        summary.append([
            ra, gamma, gammaError, r2, medianFluc, status
        ])

        if status == "accepted":
            growthRates.append((ra, gamma))

    # ========================================================
    # Format first panel
    # ========================================================

    ax1.axvspan(
        args.fit_start,
        args.fit_end,
        alpha=0.12,
        color="gray"
    )

    ax1.set_xlabel("Iteration")

    ax1.set_ylabel(
        r"$\ln(E_{\mathrm{kin}}^{\mathrm{avg}})$"
        if args.energy == "total"
        else r"$\ln(E_{\mathrm{kin}}')$"
    )

    ax1.set_title("Stage 1: Kinetic energy")
    ax1.grid(alpha=0.3)
    ax1.legend(fontsize=8)

    # ========================================================
    # Stage 2: Fit gamma versus Rayleigh
    # ========================================================

    if growthRates:

        values = np.asarray(growthRates)

        Ra = values[:, 0]
        gamma = values[:, 1]

        ax2.plot(
            Ra, gamma, "o",
            label="Measured growth rates"
        )

        ax2.axhline(
            0.0,
            color="gray",
            linestyle="--"
        )

        if (
            len(growthRates) >= 3
            and np.any(gamma < 0.0)
            and np.any(gamma > 0.0)
        ):

            a, b = np.polyfit(Ra, gamma, 1)

            RaCritical = -b / a

            if Ra.min() <= RaCritical <= Ra.max():

                Raline = np.linspace(Ra.min(), Ra.max(), 200)

                ax2.plot(
                    Raline,
                    a * Raline + b,
                    "-",
                    label=fr"$Ra_c \approx {RaCritical:.3f}$"
                )

                ax2.plot(
                    RaCritical, 0.0,
                    "D",
                    color="black"
                )

                print(f"\nEstimated Ra critical = {RaCritical:.6f}")

            else:
                print("\nZero crossing lies outside the sampled Ra range")

        else:
            print("\nNo reliable stability bracket found")

        ax2.legend(fontsize=8)

    else:
        print("\nNo accepted growth-rate fits")

    ax2.set_xlabel("Rayleigh number")
    ax2.set_ylabel("Growth rate per iteration")
    ax2.set_title("Stage 2: Critical Rayleigh number")
    ax2.grid(alpha=0.3)

    # ========================================================
    # Save figure
    # ========================================================

    fig.tight_layout()

    figurePath = output / "figure_3_13_style.png"

    fig.savefig(figurePath, dpi=180)

    plt.close(fig)

    # ========================================================
    # Save fitted values
    # ========================================================

    csvPath = output / "growth_rates.csv"

    with csvPath.open("w", newline="") as file:

        writer = csv.writer(file)

        writer.writerow([
            "Ra",
            "gamma_per_iteration",
            "gamma_stderr",
            "R2",
            "median_Efluc",
            "status"
        ])

        writer.writerows(summary)

    print(f"\nFigure saved to: {figurePath}")
    print(f"Growth rates saved to: {csvPath}")


if __name__ == "__main__":
    main()
